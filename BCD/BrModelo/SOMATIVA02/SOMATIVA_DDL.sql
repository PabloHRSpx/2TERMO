CREATE DATABASE BIBLIOTECA_PABLO_SOM2;

USE BIBLIOTECA_PABLO_SOM2;

CREATE TABLE USUARIO (
    ID_USUARIO INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20) NULL,
    ATIVO BOOLEAN DEFAULT TRUE
)

CREATE TABLE LIVRO (
    ID_LIVRO INT PRIMARY KEY AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    AUTOR VARCHAR(120) NOT NULL,
    ISBN CHAR(13) NOT NULL UNIQUE,
    ANO_PUBLICADO INT NULL,
    QUANTIDADE_DISPONIVEL INT NOT NULL DEFAULT 0,
    CONSTRAINT CK_QUANTIDADE_DISPONIVEL CHECK ( QUANTIDADE_DISPONIVEL >= 0)
)

CREATE TABLE EMPRESTIMO (
    ID_EMPRESTIMO INT PRIMARY KEY AUTO_INCREMENT,
    DATA_EMPRESTIMO DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE NULL,
    ID_USUARIO INT,
    ID_LIVRO INT,
    STATUS_EMPRESTIMO VARCHAR(20) DEFAULT 'ABERT0',
    CONSTRAINT CK_STATUS_EMPRESTIMO CHECK (STATUS_EMPRESTIMO >= 'ABERTO'),
    CONSTRAINT FK_USUARIO_EMPRESTIMO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT FK_LIVRO_EMPRESTIMO FOREIGN KEY (ID_LIVRO) REFERENCES LIVRO(ID_LIVRO) ON UPDATE CASCADE ON DELETE RESTRICT
)

